# Parsear y deduplicar manteniendo orden
seen, citas_ordered = set(), []
for tok in CITAS_RAW.split():
    tok = tok.strip()
    if tok and tok not in seen:
        seen.add(tok); citas_ordered.append(tok)
print(f"Citas unicas: {len(citas_ordered)}")

# ─── 1. BigQuery en lotes de 200 ─────────────────────────────────────────────
print("Consultando BigQuery en lotes de 200...")
client = bigquery.Client()
CHUNK = 200
all_rows = []
for i in range(0, len(citas_ordered), CHUNK):
    chunk = citas_ordered[i:i + CHUNK]
    in_vals = ", ".join(f"'{c}'" for c in chunk)
    q = f"""SELECT CAST(APPOINTMENT_NBR AS STRING) AS APPOINTMENT_NBR,
        VENDOR, CEDIS, LOCACION, NOMBRE_CEDIS, TIPO_CITA, ARRIVAL_DATE
    FROM `{BQ_TABLE}`
    WHERE CAST(APPOINTMENT_NBR AS STRING) IN ({in_vals})"""
    chunk_df = client.query(q).to_dataframe()
    all_rows.append(chunk_df)
    print(f"  Lote {i//CHUNK+1}: {len(chunk_df)} registros")

df_bq = pd.concat(all_rows, ignore_index=True) if all_rows else pd.DataFrame(
    columns=["APPOINTMENT_NBR","VENDOR","CEDIS","LOCACION","NOMBRE_CEDIS","TIPO_CITA","ARRIVAL_DATE"])
# Deduplicar por APPOINTMENT_NBR (quedarse con la mas reciente)
df_bq = df_bq.sort_values("ARRIVAL_DATE", ascending=False).drop_duplicates("APPOINTMENT_NBR")
print(f"BQ: {len(df_bq)} citas unicas encontradas")

# ─── 2. Fallback CSV local para los no encontrados ────────────────────────────
found_bq = set(df_bq["APPOINTMENT_NBR"].astype(str))
missing  = [c for c in citas_ordered if c not in found_bq]
print(f"No encontradas en BQ: {len(missing)} — buscando en YMS_24.CSV...")

df_csv_match = pd.DataFrame()
if missing and (BASE / "YMS_24.CSV").exists():
    csv_cols = ["APPOINTMENT_NBR","VENDOR","CEDIS","LOCACION","NOMBRE_CEDIS","TIPO_CITA","ARRIVAL_DATE"]
    chunks = []
    missing_set = set(missing)
    for chunk_csv in pd.read_csv(BASE / "YMS_24.CSV", encoding="latin1",
                                  usecols=csv_cols, chunksize=100_000):
        chunk_csv["APPOINTMENT_NBR"] = chunk_csv["APPOINTMENT_NBR"].astype(str)
        matched = chunk_csv[chunk_csv["APPOINTMENT_NBR"].isin(missing_set)]
        if len(matched): chunks.append(matched)
    if chunks:
        df_csv_match = pd.concat(chunks, ignore_index=True)
        df_csv_match = (df_csv_match.sort_values("ARRIVAL_DATE", ascending=False)
                        .drop_duplicates("APPOINTMENT_NBR"))
        print(f"CSV local: {len(df_csv_match)} adicionales encontradas")
    else:
        print("  CSV: ninguna adicional encontrada")

# ─── 3. Combinar resultados ───────────────────────────────────────────────────
df_found = pd.concat([df_bq, df_csv_match], ignore_index=True) if len(df_csv_match) else df_bq
df_found["APPOINTMENT_NBR"] = df_found["APPOINTMENT_NBR"].astype(str)
df_found = df_found.drop_duplicates("APPOINTMENT_NBR")
df_found["FUENTE"] = df_found["ARRIVAL_DATE"].apply(
    lambda x: "BQ" if pd.notna(x) else "CSV")
# Marcar fuente correctamente
if len(df_csv_match):
    csv_appts = set(df_csv_match["APPOINTMENT_NBR"].astype(str))
    df_found.loc[df_found["APPOINTMENT_NBR"].isin(csv_appts), "FUENTE"] = "CSV"

df_input  = pd.DataFrame({"APPOINTMENT_NBR": citas_ordered})
df_result = df_input.merge(
    df_found[["APPOINTMENT_NBR","VENDOR","CEDIS","LOCACION","NOMBRE_CEDIS","TIPO_CITA","ARRIVAL_DATE","FUENTE"]],
    on="APPOINTMENT_NBR", how="left"
)
df_result["FUENTE"] = df_result["FUENTE"].fillna("NO ENCONTRADA")

enc   = df_result["VENDOR"].notna().sum()
no_enc = df_result["VENDOR"].isna().sum()
print(f"\nTotal encontradas: {enc} | No encontradas: {no_enc}")

# ─── 4. Excel ─────────────────────────────────────────────────────────────────
out = BASE / "razones_sociales_citas_v2.xlsx"
wb  = Workbook()
ws  = wb.active
ws.title = "Razones Sociales"

hdr_fill  = PatternFill("solid", fgColor="1F4E79")
alt_fill  = PatternFill("solid", fgColor="D9E1F2")
miss_fill = PatternFill("solid", fgColor="FFD7D7")
hdr_font  = Font(bold=True, color="FFFFFF", size=10)
bold_f    = Font(bold=True, size=9)
norm_f    = Font(size=9)
red_f     = Font(bold=True, color="C00000", size=9)
center    = Alignment(horizontal="center", vertical="center")
left_a    = Alignment(horizontal="left",   vertical="center")
thin      = Side(style="thin", color="CCCCCC")
brd       = Border(left=thin, right=thin, top=thin, bottom=thin)

COLS     = ["APPOINTMENT_NBR","VENDOR","CEDIS","LOCACION","NOMBRE_CEDIS","TIPO_CITA","ARRIVAL_DATE","FUENTE"]
COL_NAMS = ["# Cita","Razon Social (VENDOR)","CEDIS","Locacion","Nombre CEDIS","Tipo Cita","Fecha","Fuente"]
COL_W    = [18, 46, 8, 22, 24, 16, 14, 12]

# Titulo
ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(COLS))
t = ws.cell(1, 1,
    f"RAZONES SOCIALES POR CITA  |  {len(citas_ordered)} citas  |  "
    f"{enc} encontradas  |  {no_enc} no encontradas")
t.fill = hdr_fill; t.font = hdr_font; t.alignment = center

# Cabecera
for j, name in enumerate(COL_NAMS, 1):
    c = ws.cell(2, j, name)
    c.fill = hdr_fill; c.font = hdr_font
    c.alignment = center; c.border = brd

# Datos
for i, row in enumerate(df_result.itertuples(index=False), 3):
    missing_row = pd.isna(row.VENDOR)
    rf = miss_fill if missing_row else (alt_fill if i % 2 == 0 else None)
    for j, col in enumerate(COLS, 1):
        val = getattr(row, col)
        cell_val = "" if (val is None or (isinstance(val, float) and pd.isna(val))) else str(val)
        dc = ws.cell(i, j, cell_val)
        dc.font = (red_f if (missing_row and j == 1)
                   else bold_f if j <= 2
                   else norm_f)
        dc.alignment = left_a if j == 2 else center
        dc.border = brd
        if rf: dc.fill = rf

# Anchos
for j, w in enumerate(COL_W, 1):
    ws.column_dimensions[get_column_letter(j)].width = w
ws.row_dimensions[1].height = 24
ws.row_dimensions[2].height = 28
ws.freeze_panes = "A3"
ws.auto_filter.ref = f"A2:{get_column_letter(len(COLS))}2"

wb.save(out)
print(f"Excel guardado: {out}")
